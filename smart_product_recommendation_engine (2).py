for path in tqdm(sample_df["image_path"]):

    image = Image.open(path).convert("RGB")

    image = preprocess(image).unsqueeze(0).to(device)

    with torch.no_grad():
        embedding = model.encode_image(image)

    embedding = embedding.cpu().numpy().flatten()

    image_embeddings.append(embedding)

"""Convert image embeddings into a NumPy array"""

image_embeddings = np.array(image_embeddings).astype("float32")

print(image_embeddings.shape)

"""Normalize image embeddings for cosine similarity search"""

faiss.normalize_L2(image_embeddings)

"""Build a FAISS index using image embeddings."""

dimension = image_embeddings.shape[1]

index = faiss.IndexFlatIP(dimension)

index.add(image_embeddings)

print(index.ntotal)

"""Accept a text query from the user."""

query = input("Search Product : ")

"""Convert the text query into an OpenCLIP text embedding."""

text = tokenizer([query]).to(device)

with torch.no_grad():

    text_embedding = model.encode_text(text)

text_embedding = text_embedding.cpu().numpy().astype("float32")

