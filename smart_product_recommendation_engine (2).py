import pandas as pd
import numpy as np
import faiss

from sentence_transformers import SentenceTransformer

"""Import required Python libraries."""

df = pd.read_csv("styles.csv", on_bad_lines="skip")

df = df[
    [
        "id",
        "productDisplayName",
        "articleType",
        "baseColour",
        "gender",
        "usage"
    ]
]

df.dropna(inplace=True)
df.reset_index(drop=True, inplace=True)

print(df.shape)

"""Create a descriptive text representation for every product."""

df["description"] = (
    df["productDisplayName"] + " " +
    df["articleType"] + " " +
    df["baseColour"] + " " +
    df["gender"] + " " +
    df["usage"]
)

"""Load the pretrained SentenceTransformer model."""

model = SentenceTransformer("all-MiniLM-L6-v2")

sample_df = df.head(1000).copy()

embeddings = model.encode(
    sample_df["description"].tolist(),
    convert_to_numpy=True,
    show_progress_bar=True
)

embeddings = embeddings.astype("float32")

faiss.normalize_L2(embeddings)

"""Select the first 1000 products for testing."""

dimension = embeddings.shape[1]

index = faiss.IndexFlatIP(dimension)

index.add(embeddings)

print(index.ntotal)

"""Convert product descriptions into semantic embeddings."""

k = 5

distances, indices = index.search(
    embeddings,
    k
)

THRESHOLD = 0.90

visited = set()

groups = []

for i in range(len(sample_df)):

    if i in visited:
        continue

    group = []

    for score, idx in zip(distances[i], indices[i]):

        if score >= THRESHOLD:

            group.append(idx)

            visited.add(idx)

    groups.append(group)

unique_products = []

for group in groups:

    unique_products.append(
        sample_df.iloc[group[0]]
    )

unique_catalog = pd.DataFrame(unique_products)

print(unique_catalog.shape)

unique_catalog.to_csv(
    "unique_product_catalog.csv",
    index=False
)

print("Catalog Saved Successfully!")

"""Display groups of duplicate products."""

for group in groups[:5]:

    print("=" * 50)

    print(
        sample_df.iloc[group][
            [
                "productDisplayName",
                "articleType"
            ]
        ]
    )

"""Visualize the original versus unique catalog size."""

import matplotlib.pyplot as plt

plt.figure(figsize=(6,4))

plt.bar(
    ["Original Products", "Unique Products"],
    [len(sample_df), len(unique_catalog)]
)

plt.title("Duplicate Removal using AI Embeddings")

plt.ylabel("Number of Products")

plt.show()

